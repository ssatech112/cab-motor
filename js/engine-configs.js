function buildEngineConfig(car) {
  const base = ENGINE_BY_CAR[car.id] || ENGINE_BY_CAR.maniac;
  const sound = base.sound ? { ...base.sound } : undefined;
  if (sound && typeof sound.gain === "number") {
    sound.gain = sound.gain * 0.9;
  }
  const cfg = {
    idleRpm: base.idleRpm ?? car.idle,
    redlineRpm: base.redlineRpm ?? car.redline,
    firing: base.firing,
    sound,
  };
  if (base.type) cfg.type = base.type;
  return cfg;
}
